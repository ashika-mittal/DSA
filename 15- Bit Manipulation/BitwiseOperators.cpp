#include<iostream>
#include<vector>

using namespace std;

//Bitwise Operators 

int main(){
    cout<< (3 & 5) <<endl;
    cout<< (3 | 5) <<endl;
    cout<< (3 ^ 5) <<endl;
    cout<< ~6 <<endl;
    cout<< ~4 <<endl;
    cout<< ~0 <<endl;
    cout<< ~1 <<endl;
    
    cout<< (7<<2) <<endl;
    cout<< (7>>2) <<endl;
}